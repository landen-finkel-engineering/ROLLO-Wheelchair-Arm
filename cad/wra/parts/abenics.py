"""ABENICS 3-DoF wrist for WRA-1A (B-rep parts; the toothed CS-gear and monopole surfaces are
generated by parts/abenics_mesh.py because exact B-rep booleans of two crossed spherical tooth
families exceed practical OCCT memory/time - see docs/06_abenics_wrist.md).

Frames
  A  : housing frame. Origin = sphere centre, x = tool axis at home, y/z = forearm y/z (A is F
       translated to (L3, YC, 0)).
  S  : CS-gear body frame: X = body g, Y = body h, Z = body i (tool axis).  At home S->A maps
       g -> u1 = (0, s, s), h -> u2 = (0, -s, s), i -> x_A.
  M_k: module frame (fixed): z = u_k, x = x_A, y = z x x.
  Cq : carrier frame = M_k rotated by q about z.  x = monopole spin axis I_m, y = w, z = u_k.
  Mp : monopole frame = Cq * Pos(0, 0, D_MP) * Rot(about x by Theta).  Local X = spin axis,
       local Z = pole axis (its tooth-gap pole at -Z faces the sphere centre).
"""
