# ============================================================================ frames / poses
def S_to_A_home() -> Location:
    return Plane(origin=(0, 0, 0), x_dir=tuple(K.U[1]), z_dir=tuple(K.I_AX)).location


def S_loc(R) -> Location:
    """CS-gear (S frame) location in A for sphere orientation R (columns g, h, i in A)."""
    return Plane(origin=(0, 0, 0), x_dir=tuple(R[:, 0]), z_dir=tuple(R[:, 2])).location


def G_in_S() -> Location:
    """Tool-flange G frame inside S: X_G = Z_S (tool axis), Z_G = 'up' at home = (g+h)/sqrt2."""
    return Plane(origin=(0, 0, FL1), x_dir=(0, 0, 1), z_dir=(s2, s2, 0)).location


def M_loc(k: int) -> Location:
    x, y, z = K.module_frame(k)
    return Plane(origin=(0, 0, 0), x_dir=tuple(x), z_dir=tuple(z)).location


def Cq_loc(k: int, q: float) -> Location:
    """Carrier frame for carrier angle q (rad)."""
    return M_loc(k) * Rot(0, 0, math.degrees(q))


def Mp_loc(k: int, q: float, theta: float) -> Location:
    return Cq_loc(k, q) * Pos(0, 0, D_MP) * Rot(math.degrees(theta), 0, 0)


def ts_loc() -> Location:
    """Theta servo in the carrier frame: output (servo +z) toward -x (gear plane), servo x -> -u."""
    return Plane(origin=TS_ORIGIN, x_dir=(0, 0, -1), z_dir=(-1, 0, 0)).location


def qs_loc() -> Location:
    """q servo in the module frame."""
    return Plane(origin=QS_ORIGIN, x_dir=(1, 0, 0), z_dir=(0, 0, -1)).location


# ============================================================================ CS-gear blanks (S frame)
def _flange_inserts():
    out = []
    for i in range(TF.n):
        yg, zg, _ = lib.polar(TF.bolt_circle / 2, 90 * i)
        out.append((yg * s2 + zg * s2, -yg * s2 + zg * s2))
    yg, zg, _ = lib.polar(TF.bolt_circle / 2, 45)
    dowel = (yg * s2 + zg * s2, -yg * s2 + zg * s2)
    return out, dowel


JOINT_R = 17.0
JOINT_ANG = (45.0, 135.0, 225.0, 315.0)      # between the ring axes
DOWEL_ANG = (0.0, 180.0)


def cs_front_blank() -> Part:
    body = Sphere(R_TIP) & box(-40, 40, -40, 40, 0, 40)
    # output boss (conical, printable dome-up) + tool flange WRA-TF30
    body += Pos(0, 0, 18.0) * Cone(13.0, 17.0, FL0 - 18.0 + 0.01, align=lib.MIN_Z)
    body += cyl(TF.dia, TF.t, z=FL0)
    body -= Sphere(SOCK_R)
    body -= cyl(7.0, FL1 + 2, z=-1)                                  # J6 cable channel
    body -= cyl(TF.center_bore, 4.0, z=FL1 - 4.0 + 0.01)
    ins, dw = _flange_inserts()
    for x, y in ins:
        body -= cyl(lib.ins_hole("M3"), lib.ins_depth("M3") - 1.0, x, y, FL1 - lib.ins_depth("M3") + 1.01)
    body -= cyl(TF.dowel_dia - P.fit.pin_press_minus, 4.0, dw[0], dw[1], FL1 - 4.0 + 0.01)
    # hemisphere joint: 4x M3 from the front cap, 2x 3 mm dowels
    for a in JOINT_ANG:
        x, y, _ = lib.polar(JOINT_R, a)
        body -= cyl(clr("M3"), 40, x, y, -1)
        body -= cyl(6.2, 40, x, y, 9.0)                              # head counterbore (head sits at z ~9)
    for a in DOWEL_ANG:
        x, y, _ = lib.polar(JOINT_R, a)
        body -= cyl(3.0 + 0.05, 6.0, x, y, -0.01)
    return body


def post_opening() -> Part:
    """Swept clearance of the fixed post (dia post_od + 1) for tool tilts up to tilt_hard."""
    a = math.radians(AB.tilt_hard_deg + 1.0)
    r_post = AB.post_od / 2 + 0.6
    apex = r_post / math.sin(a)
    h = apex + R_TIP + 5
    return Pos(0, 0, apex) * Rot(180, 0, 0) * Cone(0.01, h * math.tan(a), h, align=lib.MIN_Z)


def cs_back_blank() -> Part:
    body = Sphere(R_TIP) & box(-40, 40, -40, 40, -40, 0)
    body -= Sphere(SOCK_R)
    body -= post_opening() & box(-40, 40, -40, 40, -40, 0.01)
    for a in JOINT_ANG:
        x, y, _ = lib.polar(JOINT_R, a)
        body -= cyl(lib.ins_hole("M3"), lib.ins_depth("M3"), x, y, -lib.ins_depth("M3") + 0.01)
    for a in DOWEL_ANG:
        x, y, _ = lib.polar(JOINT_R, a)
        body -= cyl(3.0 - P.fit.pin_press_minus, 6.0, x, y, -6.0 + 0.01)
    return body


# ============================================================================ monopole blank (Mp frame)
def monopole_blank() -> Part:
    w = AB.mp_width / 2
    body = Sphere(RM_TIP) & box(-w, w, -20, 20, -20, 20)
    # Theta drive gear (spur, axis = X) on the -X side, tooth on +/-Z at Theta = 0
    g = Pos(TG_X[0], 0, 0) * Rot(0, 90, 0) * lib.spur_gear(TG.module, TG.mp_teeth, TG.width)
    # tip relief: the gear's inner tip corner (x = -6, r = 12.75) would reach 26.2 mm from the sphere
    # centre, inside the CS tooth tips (27.0).  Remove everything the CS tip sphere (+ TG_RELIEF_CLR)
    # can sweep while the monopole spins = a torus (major radius D_MP, minor R_TIP + clr) about X.
    # Leaves >= 0.27 mm addendum at the inner face (contact ratio there ~1.0, 1.5 at the outer face).
    g -= Rot(0, 90, 0) * Torus(D_MP, R_TIP + TG_RELIEF_CLR)
    body += g
    body += cyl(20.0, -w - TG_X[1] + 0.6, TG_X[1] - 0.01, 0, 0, axis="X")      # hub gear <-> disc
    # 2x 688 in the disc; the hub face only touches the bearing OUTER race; the -x spacer
    # (part 93, on the pin) passes through the gear bore to the inner race
    body -= cyl(lib.seat("688"), 2 * w + 0.02, -w - 0.01, 0, 0, axis="X")
    body -= cyl(12.0, 1.2, -w - 1.1, 0, 0, axis="X")
    body -= cyl(11.0, 20, -w - 19.0, 0, 0, axis="X")
    return body


def mp_spacer() -> Part:
    """Pin spacer between the -x fork arm and the -x 688 inner race (Cq frame, axis x at u = D_MP)."""
    x0, x1 = ARM_N[1], -AB.mp_width / 2
    return Pos(0, 0, D_MP) * (cyl(10.5, x1 - x0, x0, 0, 0, axis="X") - cyl(PIN_D + 0.2, x1 - x0 + 2, x0 - 1, 0, 0, axis="X"))


# ============================================================================ carrier, part 1: fork (Cq frame)
def _arm(x0, x1, half_w=8.0) -> Part:
    """Fork arm (plate normal to x) from a rounded pin boss up to the shoulder ring."""
    a = box(x0, x1, -half_w, half_w, D_MP, SHOULDER[1]) + cyl(2 * half_w, x1 - x0, x0, 0, D_MP, axis="X")
    return a


def mp_fork() -> Part:
    """Part 1 of the carrier: two arms carry the monopole pin, a ring carries the 6808 inner
    race (near-side shoulder; the cradle sleeve clamps the far side).  Everything here stays
    inside r = 21.75 so the fork (with its bearing) drops into the module-frame holder."""
    ring = cyl(SEAT_OD, RING_END - SHOULDER[0], z=SHOULDER[0]) + cyl(43.5, SHOULDER[1] - SHOULDER[0], z=SHOULDER[0])
    ring -= cyl(2 * FORK_BORE_R, 40, z=SHOULDER[0] - 5)
    body = ring + _arm(*ARM_N, half_w=ARM_N_HW) + _arm(*ARM_P)
    # bridge: +x arm -> ring (outside the monopole disc sweep |x| <= 5.5)
    body += box(ARM_P[0], FORK_BORE_R + 1.0, -6.0, 6.0, D_MP + 2.0, SHOULDER[1])
    body += box(ARM_N[0], ARM_N[1], -ARM_N_HW, ARM_N_HW, D_MP + 2.0, SHOULDER[1])
    # monopole sweep (disc |x|<=5 spinning about x) + drive gear sweep + clearances
    body -= Pos(0, 0, D_MP) * (cyl(2 * (RM_TIP + 0.6), 2 * (AB.mp_width / 2 + 0.6), -(AB.mp_width / 2 + 0.6), 0, 0, axis="X"))
    body -= Pos(0, 0, D_MP) * cyl(2 * (TG.module * TG.mp_teeth / 2 + TG.module + 0.6), TG_X[1] - TG_X[0] + 1.0,
                                   TG_X[0] - 0.5, 0, 0, axis="X")
    # inner-race contact boss on the +x arm (only the inner race touches)
    body += Pos(0, 0, D_MP) * cyl(10.5, ARM_P[0] - AB.mp_width / 2, AB.mp_width / 2, 0, 0, axis="X")
    # pin: press in the -x arm, slip in the +x arm
    body -= cyl(PIN_D - P.fit.pin_press_minus, ARM_N[1] - ARM_N[0] + 2, ARM_N[0] - 1, 0, D_MP, axis="X")
    body -= cyl(PIN_D + 0.05, 30, ARM_N[1] - 0.01, 0, D_MP, axis="X")
    # 2x radial M3 (self-tapping, from the cradle sleeve) at +/-y
    for sgn in (1, -1):
        body -= Pos(0, sgn * (FORK_BORE_R - 1.0), SLEEVE_SCREW_U) * Rot(-90 * sgn, 0, 0) * cyl(2.5, 6.0)
    return body


# ============================================================================ carrier, part 2: Theta cradle (Cq frame)
def mp_cradle() -> Part:
    """Part 2 of the carrier: sleeve over the fork ring (clamps the 6808 inner race, 2x radial
    M3), U-channel around the Theta servo (open on the gear side, closed by the strap), end
    plate and hub on the 6805 floating bearing with the two q-drive dog slots."""
    bx, by, bz = TS_BODY["x"], TS_BODY["y"], TS_BODY["z"]
    sleeve = cyl(SLEEVE_OD, SLEEVE[1] - SLEEVE[0], z=SLEEVE[0]) - cyl(SEAT_OD + 0.2, 20, z=SLEEVE[0] - 1)
    walls = box(CR_X[0], CR_X[1], -CR_Y, CR_Y, CR_U0, END_PLATE[1])
    body = sleeve + walls
    body -= box(CR_X[0] - 1, bx[1], by[0], by[1], CR_U0 - 1, bz[1])        # channel (servo goes in from -x)
    # end plate across the whole width + hub
    body += box(-14.0, CR_X[1], -CR_Y, CR_Y, END_PLATE[0], END_PLATE[1])
    body += cyl(29.0, HUB_SH[1] - HUB_SH[0] + 0.01, z=HUB_SH[0] - 0.01)
    body += cyl(d6805 - 0.02, HUB_END - HUB_SH[1] + 0.01, z=HUB_SH[1] - 0.01)
    body -= cyl(SEAT_OD + 0.2, RING_END + 0.4 - SLEEVE[0] + 1, z=SLEEVE[0] - 1)   # fork ring (slide fit)
    body -= ts_loc() * lib.servo_envelope(CL, horn=True)
    body -= cyl(6.0, 20, z=END_PLATE[0] - 1)
    for a in (0.0, 180.0):
        x, y, _ = lib.polar(DOG_R, a)
        body -= box(x - DOG_W / 2 - 1.5, x + DOG_W / 2 + 1.5, y - DOG_W / 2, y + DOG_W / 2, HUB_END - DOG_DEPTH, HUB_END + 1)
    # sleeve must not reach into the Theta-gear sweep; fork-ring screws (countersunk M3)
    body -= Pos(0, 0, Z_TS) * cyl(2 * (R_TG_SERVO + TG.module + 0.5), TG_X[1] - TG_X[0] + 1.0, TG_X[0] - 0.5, 0, 0, axis="X")
    for sgn in (1, -1):
        zc = SLEEVE_SCREW_U
        body -= Pos(0, sgn * SLEEVE_OD / 2, zc) * Rot(90 * sgn, 0, 0) * cyl(clr("M3"), 6.0)
        body -= Pos(0, sgn * SLEEVE_OD / 2, zc) * Rot(90 * sgn, 0, 0) * Cone(3.3, 1.6, 1.7, align=lib.MIN_Z)
    # Theta-servo cable: connector exit through the base
    k = S.connector
    u0, u1 = TS_ORIGIN[2] - k.x[1] - 0.5, TS_ORIGIN[2] - k.x[0] + 0.5
    body -= box(bx[1] - 1, CR_X[1] + 1, k.y[0] - 0.5, k.y[1] + 0.5, u0, u1)
    # strap inserts (2x M3 in the -x end faces of the side walls)
    for y in strap_y():
        body -= cyl(lib.ins_hole("M3"), lib.ins_depth("M3"), CR_X[0] - 0.01, y, 0.5 * (STRAP_U[0] + STRAP_U[1]), axis="X")
    return body


def strap_y():
    return (-(TS_BODY["y"][1] + CR_WALL / 2), TS_BODY["y"][1] + CR_WALL / 2)


def cradle_strap() -> Part:
    x0 = CR_X[0]
    st = box(x0 - 3.5, x0, -CR_Y, CR_Y, STRAP_U[0], STRAP_U[1])
    for y in strap_y():
        st -= cyl(clr("M3"), 6, x0 - 4.5, y, 0.5 * (STRAP_U[0] + STRAP_U[1]), axis="X")
    return st


def theta_gear() -> Part:
    """Theta drive gear (20T m1.5) on the Theta-servo horn (Cq frame)."""
    # tooth/gap phasing: the monopole gear (tooth at its local +X -> -Z) shows the servo gear a gap
    # when mp_teeth is odd and a tooth when even; the servo gear must show the opposite
    ph = 0.0 if TG.mp_teeth % 2 else 180.0 / TG.servo_teeth
    g = Rot(0, 0, ph) * lib.spur_gear(TG.module, TG.servo_teeth, TG.width)
    g -= cyl(9.0, TG.width + 2, z=-1)
    for x, y in lib.horn_bolt_xy():
        g -= cyl(clr("M3"), TG.width + 2, x, y, -1)
    return Pos(TG_X[0], 0, Z_TS) * Rot(0, 90, 0) * g


def q_coupling() -> Part:
    """Bolted to the q-servo horn (M frame); 2 dogs drive the cradle hub (torque only - the
    carrier is carried by its own 6808 + 6805, never by the servo shaft)."""
    z0, z1 = CPL_DISC
    body = cyl(22.0, z1 - z0, z=z0)
    for a in (0.0, 180.0):
        x, y, _ = lib.polar(DOG_R, a)
        body += box(x - (DOG_W - 0.6) / 2 - 1.2, x + (DOG_W - 0.6) / 2 + 1.2, y - (DOG_W - 0.6) / 2,
                    y + (DOG_W - 0.6) / 2, HUB_END - DOG_DEPTH + 0.5, z0 + 0.01)
    for x, y in lib.horn_bolt_xy():
        body -= cyl(clr("M3"), 10, x, y, z0 - 6)
        body -= cyl(6.0, 2.0, x, y, z0 - 0.01)
    body -= cyl(7.0, 2.0, z=z1 - 1.7)                                     # horn centre-screw head
    return body


# ============================================================================ module frame (M frame)
def module_frame() -> Part:
    """Fixed frame of one module: 6808 holder (near lip), lug to the housing, strut behind the
    carrier sweep, 6805 boss (far lip), q-servo cradle."""
    holder = cyl(HOLDER_OD, HOLDER[1] - HOLDER[0], z=HOLDER[0])
    holder -= cyl(D6808 + 0.1, BRG_Z[1] - BRG_Z[0] + 1, z=BRG_Z[0])
    holder -= cyl(46.0, 5, z=HOLDER[0] - 1)
    lug = box(LUG["x"][0], LUG["x"][1], -LUG["y"], LUG["y"], *LUG["z"])
    strut = box(STRUT["x"][0], STRUT["x"][1], -STRUT["y"], STRUT["y"], HOLDER[0], QS_BODY["z"][1] + QW)
    qx, qy, qz = QS_BODY["x"], QS_BODY["y"], QS_BODY["z"]
    boss = cyl(D6805 + 7.0, QB[1] - QB[0], z=QB[0])
    bridge = box(STRUT["x"][0], -12.0, -STRUT["y"] - 2, STRUT["y"] + 2, QB[0], QB[1])
    qcr = box(qx[0] - QW, qx[1] + QW, qy[0] - QW, qy[1] + QW, QB[1] - 0.01, qz[1] + QW)
    arm = box(STRUT["x"][0], qx[0] - QW + 0.01, -STRUT["y"], STRUT["y"], QB[0], qz[1] + QW)
    body = holder + lug + strut + boss + bridge + qcr + arm
    # q-cap bosses on the outside of the y-walls (added before the servo pocket is cut, so the pocket stays clear)
    for x, y in q_cap_xy():
        body += cyl(Q_BOSS_D, 9.0, x, y, qz[1] + QW - 9.0)
    body -= cyl(D6808 + 0.1, BRG_Z[1] - BRG_Z[0] + 0.02, z=BRG_Z[0] - 0.01)
    body -= cyl(46.0, 5, z=HOLDER[0] - 1)
    body -= cyl(lib.seat(AB.far_bearing), FAR_BRG_Z[1] + 0.05 - QB[0] + 0.01, z=QB[0] - 0.01)
    body -= cyl(33.0, 3, z=QB[1] - 1.5)
    body -= qs_loc() * lib.servo_envelope(CL)
    body -= cyl(24.0, QH_Z - QB[1] + 2.5, z=QB[1] - 1.0)                 # coupling / horn window
    body -= box(qx[0] - QW - 1, qx[0] + 5, qy[0] + 3, qy[1] - 3, qz[0] + 6, qz[1] - 4)   # cable window (rear)
    # holder retainer inserts (3x M3 in the holder far face)
    for a in (90.0, 210.0, 330.0):
        x, y, _ = lib.polar(0.25 * (HOLDER_OD + D6808), a)
        body -= cyl(lib.ins_hole("M3"), lib.ins_depth("M3"), x, y, HOLDER[1] - lib.ins_depth("M3") + 0.01)
    # 2x M4 (low head) through the lug into the housing pad
    for x, y in LUG_BOLTS:
        body -= cyl(clr("M4"), 30, x, y, HOLDER[0] - 1)
    # q-cap: 4x M3 thread-forming (2.5 mm pilots) in those bosses
    for x, y in q_cap_xy():
        body -= cyl(2.5, 8.5, x, y, qz[1] + QW - 8.5 + 0.01)
    return body


def holder_retainer() -> Part:
    r = cyl(HOLDER_OD, RET[1] - RET[0], z=RET[0]) - cyl(RET_ID, 5, z=RET[0] - 1)
    for a in (90.0, 210.0, 330.0):
        x, y, _ = lib.polar(0.25 * (HOLDER_OD + D6808), a)
        r -= cyl(clr("M3"), 6, x, y, RET[0] - 1)
        r -= Pos(x, y, RET[1] - 1.7) * Cone(clr("M3") / 2, 3.3, 1.71, align=lib.MIN_Z)   # countersunk (flush)
    return r


Q_BOSS_D = 8.0


def q_cap_xy():
    """q-cap screws: in the y-walls, 5 mm in from the ends, 2.25 mm out from the pocket (boss centres)."""
    qx, qy = QS_BODY["x"], QS_BODY["y"]
    return [(qx[0] + 5.0, qy[0] - 2.25), (qx[0] + 5.0, qy[1] + 2.25), (qx[1] - 5.0, qy[0] - 2.25), (qx[1] - 5.0, qy[1] + 2.25)]


def q_cap() -> Part:
    qx, qy, qz = QS_BODY["x"], QS_BODY["y"], QS_BODY["z"]
    W = QW
    cap = box(qx[0] - W, qx[1] + W, qy[0] - W - 3.0, qy[1] + W + 3.0, qz[1] + W, qz[1] + W + 3.0) - \
        box(qx[0] + 4, qx[1] - 4, qy[0] + 3, qy[1] - 3, qz[1] + W - 1, qz[1] + W + 4)
    for x, y in q_cap_xy():
        cap -= cyl(clr("M3"), 6, x, y, qz[1] + W - 1)
    return cap


