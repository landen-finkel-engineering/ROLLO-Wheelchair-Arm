POST_X = (-62.0, -BALL_R + 1.0)


def center_ball() -> Part:
    b = Sphere(BALL_R)
    b -= cyl(AB.post_od + 0.1, BALL_R + 0.5, -BALL_R - 1.0, 0, 0, axis="X")   # post bore (bond + M2 cross pin)
    b -= cyl(5.0, BALL_R + 1.0, -0.5, 0, 0, axis="X")                          # cable exit toward the tool
    b -= cyl(2.0, 2 * BALL_R + 2, -BALL_R + 4.0, -BALL_R - 1, 0, axis="Y")     # M2 cross pin
    return b


def post() -> Part:
    return cyl(AB.post_od, POST_X[1] - POST_X[0], POST_X[0], 0, 0, axis="X") - \
        cyl(AB.post_od - 2.0, POST_X[1] - POST_X[0] + 2, POST_X[0] - 1, 0, 0, axis="X")


def housing() -> Part:
    """Forearm tube sockets -> spine -> post clamp + two shoulders for the module frames."""
    from .arm import tube_bosses, tube_sockets, SOCK_LEN
    from .wrist import X_WS
    L3 = P.arm.L3
    xs1 = X_WS - L3                      # socket bottom in A (-113)
    xs0 = xs1 - SOCK_LEN
    offs = (P.arm.fa_tube_offset, -P.arm.fa_tube_offset)
    body = tube_bosses(xs0 - 4, xs1 + 4, offs, 0.0)
    spine = box(xs0, -40.0, -9.0, 9.0, -P.arm.fa_tube_offset - 5, P.arm.fa_tube_offset + 5)
    body += spine
    # post clamp boss
    body += cyl(20.0, 22.0, -62.0, 0, 0, axis="X")
    body -= cyl(AB.post_od - P.fit.pin_press_minus, 30, -64.0, 0, 0, axis="X")
    body -= box(-63.0, -38.0, -0.75, 0.75, 0, 12)                          # clamp slit
    body -= cyl(clr("M3"), 30, -51.0, -15, 6.0, axis="Y")
    # shoulders: one pad under each module-frame lug (2x M4 low-head along u into inserts)
    for k in (1, 2):
        Mk = M_loc(k)
        body += Mk * box(LUG["x"][0], LUG["x"][1], -LUG["y"], LUG["y"], PAD_U[0], PAD_U[1])
        c = (Mk * Pos(0.5 * (LUG["x"][0] + LUG["x"][1]), 0, 0.5 * (PAD_U[0] + PAD_U[1]))).position
        body += _bar(Vector(-48.0, 0, 0), c, 14.0)
        for x, y in LUG_BOLTS:
            body -= Mk * Pos(x, y, PAD_U[1] + 0.01) * Rot(180, 0, 0) * cyl(lib.ins_hole("M4"), lib.ins_depth("M4"))
    body -= cyl(AB.post_od + 0.6, 40.0, -40.5, 0, 0, axis="X")              # post passes freely beyond the clamp
    body -= tube_sockets(xs0 - 4.02, xs1, offs, 0.0, cross_x=xs0 + SOCK_LEN / 2)
    body -= Sphere(R_TIP + 2.0)
    return body


def _bar(p0: Vector, p1: Vector, d: float) -> Part:
    v = p1 - p0
    z = v.normalized()
    x = Vector(0, 1, 0) if abs(z.Y) < 0.9 else Vector(1, 0, 0)
    pl = Plane(origin=p0, z_dir=z, x_dir=(x - z * x.dot(z)).normalized())
    return pl.location * box(-d / 2, d / 2, -d / 2, d / 2, 0, v.length)


