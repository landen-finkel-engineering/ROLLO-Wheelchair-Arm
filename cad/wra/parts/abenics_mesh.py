"""Toothed ABENICS gears as watertight meshes (manifold3d), from the B-rep blanks in abenics.py.

Why meshes: the cross-spherical (CS) gear is the intersection of two spherical gears whose ring
teeth cross each other (two orthogonal families).  In OCCT this boolean grows past 4 GB / 30 min
on a laptop; manifold3d does it exactly on a fine mesh in ~2 s.  The B-rep blanks (everything
except the tooth grooves) are still exported as STEP; the print files are these meshes.

S-gear (spherical gear): a 2-D involute gear profile revolved about one of its diameters.
CS-gear = S-gear about body X (g)  INTERSECT  S-gear about body Y (h).
Monopole = S-gear about its pole axis (Z), cut to a disc |x| <= w/2 (x = spin axis).
"""
from __future__ import annotations

import functools
import math
import pathlib
import tempfile

import numpy as np
import manifold3d as m3
import trimesh

from ..config import P
from .. import lib
from . import abenics as ab

AB = P.abenics


def half_profile(module, teeth, backlash):
    pts = lib.involute_gear_profile(module, teeth, backlash, n_inv=12)
    up = []
    for x, y in pts:
        a = math.atan2(y, x)
        if 1e-9 < a < math.pi - 1e-9:
            up.append((a, x, y))
    up.sort(key=lambda t: t[0])
    ra = module * teeth / 2 + module
    rf = module * teeth / 2 - 1.25 * module
    end = (-ra, 0.0) if teeth % 2 == 0 else (-rf, 0.0)    # even: tooth at both poles; odd: gap at -pole
    return [(ra, 0.0)] + [(x, y) for _, x, y in up] + [end]


@functools.lru_cache(maxsize=4)
def s_gear(module, teeth, segs):
    """Spherical gear, ring teeth about Z; tooth tip at +Z pole."""
    poly = half_profile(module, teeth, AB.backlash)
    cs = m3.CrossSection([[(y, x) for x, y in poly][::-1]])      # (radial, axial), CCW
    return m3.Manifold.revolve(cs, segs)


@functools.lru_cache(maxsize=1)
def cs_teeth():
    g = s_gear(AB.module, AB.cs_teeth, AB.segments)
    gx = g.rotate([0, 90, 0])          # rings about X (body g)
    gy = g.rotate([-90, 0, 0])         # rings about Y (body h)
    return gx ^ gy


def part_to_manifold(part, tol=0.01) -> m3.Manifold:
    from build123d import export_stl
    with tempfile.TemporaryDirectory() as d:
        f = pathlib.Path(d) / "p.stl"
        export_stl(part, str(f), tolerance=tol, angular_tolerance=0.05)
        tm = trimesh.load(str(f))
    mesh = m3.Mesh(vert_properties=np.asarray(tm.vertices, np.float32), tri_verts=np.asarray(tm.faces, np.uint32))
    return m3.Manifold(mesh)


def band_region(rmax=40.0) -> m3.Manifold:
    """|z| <= r_xy * tan(BAND): colatitudes 90 +/- BAND about Z."""
    half = 90.0 - ab.BAND
    h = rmax
    cone = m3.Manifold.cylinder(h, 0.0, h * math.tan(math.radians(half)), 192)
    cyl = m3.Manifold.cylinder(2 * rmax, rmax, rmax, 192).translate([0, 0, -rmax])
    return cyl - cone - cone.mirror([0, 0, 1])


def slab(w, r=30.0) -> m3.Manifold:
    return m3.Manifold.cube([2 * w, 2 * r, 2 * r]).translate([-w, -r, -r])


@functools.lru_cache(maxsize=2)
def cs_hemisphere(which: str) -> m3.Manifold:
    blank = part_to_manifold(ab.cs_front_blank() if which == "front" else ab.cs_back_blank())
    outer = m3.Manifold.sphere(ab.R_TIP + 0.5, 4 * AB.segments // 3)
    grooves = (outer - cs_teeth()) ^ band_region()
    return blank - grooves


@functools.lru_cache(maxsize=1)
def monopole(step_deg: float = 1.0) -> m3.Manifold:
    """Monopole GENERATED by the CS-gear's ring teeth (hobbing simulation, as for the original
    ABENICS MP-gear): blank minus the swept S-gear over the rolling motion.  In the monopole
    frame the sphere centre orbits by -Theta about x and the sphere spins -Theta/2 (2:1 mesh),
    i.e. T(Theta) = Rot_x(-Theta) . Trans(0,0,-D) . Rot_x(-Theta/2).  |Theta| <= 180 deg
    (body-axis tilt alpha <= 90 deg) so each monopole surface patch is generated once."""
    blank = part_to_manifold(ab.monopole_blank())
    w = AB.mp_width / 2 + 0.5
    ring = s_gear(AB.module, AB.cs_teeth, AB.segments)                  # rings about Z, tooth at +Z
    slab_s = ring ^ slab(w + 0.5, r=40.0)                               # rotation about x keeps |x| invariant
    near = m3.Manifold.cube([2 * w, 2 * (ab.RM_TIP + 1.0), 2 * (ab.RM_TIP + 1.0)]).translate(
        [-w, -(ab.RM_TIP + 1.0), -(ab.RM_TIP + 1.0)])
    pieces = []
    n = int(round(360.0 / step_deg))
    for i in range(n + 1):
        th = -180.0 + i * step_deg
        sw = slab_s.rotate([-th / 2, 0, 0]).translate([0, 0, -ab.D_MP]).rotate([-th, 0, 0])
        pc = sw ^ near
        if not pc.is_empty():
            pieces.append(pc)
    swept = m3.Manifold.batch_boolean(pieces, m3.OpType.Add)
    disc = slab(AB.mp_width / 2 + 0.01, r=30.0)
    return blank - (swept ^ disc)


def to_trimesh(mf: m3.Manifold) -> trimesh.Trimesh:
    mesh = mf.to_mesh()
    v = np.asarray(mesh.vert_properties)[:, :3]
    f = np.asarray(mesh.tri_verts)
    return trimesh.Trimesh(v, f, process=False)


def loc_matrix(loc) -> list:
    """build123d Location -> 3x4 affine matrix for manifold3d.transform."""
    t = loc.wrapped.Transformation()
    return [[t.Value(i, j) for j in range(1, 5)] for i in range(1, 4)]


def export(out_dir: pathlib.Path, print_locs: dict):
    """Write the toothed print STLs (in print orientation) and return mesh stats."""
    stats = {}
    for name, mf in (("80_cs_gear_front", cs_hemisphere("front")), ("81_cs_gear_back", cs_hemisphere("back")),
                     ("82_monopole", monopole())):
        loc = print_locs.get(name)
        m_ = mf.transform(loc_matrix(loc)) if loc is not None else mf
        tm = to_trimesh(m_)
        tm.export(str(out_dir / f"{name}.stl"))
        clean = lib.stl_clean(out_dir / f"{name}.stl")      # float32 rounding leaves a few zero-area slivers
        stats[name] = {"triangles": int(len(tm.faces)), "watertight": clean["watertight"], "bodies": clean["bodies"],
                       "volume_mm3": round(float(tm.volume), 1), "status": str(mf.status()),
                       "genus": int(mf.genus()), "zmin": round(float(tm.bounds[0][2]), 3)}
    return stats
